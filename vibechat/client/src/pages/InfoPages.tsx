export function SupportPage({ appName, supportEmail }: { appName: string; supportEmail: string | null }) {
  return (
    <DocPage appName={appName} title="Поддержка">
      {supportEmail ? (
        <p>
          Напишите нам: <a className="text-accent underline" href={`mailto:${supportEmail}`}>{supportEmail}</a>. Если вас
          заблокировали по ошибке — укажите примерное время блокировки.
        </p>
      ) : (
        <p>Контакт поддержки пока не настроен администратором сайта.</p>
      )}
      <h2>Частые вопросы</h2>
      <h3 className="font-semibold">Не работает камера</h3>
      <p>
        Разрешите доступ к камере в настройках браузера (значок слева от адреса сайта). Закройте другие приложения, которые
        используют камеру. Сайт должен открываться по https://.
      </p>
      <h3 className="font-semibold">Собеседник найден, но видео не появляется</h3>
      <p>
        Некоторые мобильные и корпоративные сети блокируют прямые соединения. Мы автоматически попробуем соединиться ещё
        раз или подберём другого собеседника. Попробуйте сменить сеть (Wi-Fi ↔ мобильный интернет).
      </p>
      <h3 className="font-semibold">Как пожаловаться</h3>
      <p>Во время разговора или сразу после него нажмите «Пожаловаться» в верхней части видео.</p>
      <h3 className="font-semibold">Горячие клавиши</h3>
      <p>Esc — следующий собеседник (когда курсор не в поле чата). Enter — отправить сообщение, Shift+Enter — новая строка.</p>
    </DocPage>
  );
}

